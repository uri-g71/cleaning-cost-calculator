// Each expression is a native XLSX formula using references to the actual quote and group.
// The application engine supplies cached values for viewers that do not recalculate.
import type {RowId} from "./report";
export type PriceKey=RowId|"p125"|"p150";
export interface ExcelRefs {
 p:Record<string,string>; c:Record<PriceKey,string>; b:Record<PriceKey,string>; h:Record<string,string>;
 base:string;sector:string;basis:string;sickRate:string;years:string;week:string;hours:string;hours125:string;hours150:string;
}
export function excelRules({p,c,b,h,base,sector,basis,sickRate,years,week,hours,hours125,hours150}:ExcelRefs){
 return {
  costs:{
   wage: `${base}`,
   vacation: `IF(${hours}>0,(${c.wage}+${c.tenure})*${h.vacDays}*${h.day}/${h.vacDiv},0)`,
   tenure: `IF(${years}<1,0,IF(${years}<5,${p.tenureEarly},${p.tenureLate}))`,
   holiday: `IF(${p.holidayBackToBack}=1,0,(${c.wage}+${c.tenure})*${p.holidays}*${h.day}/${h.annual})`,
   recovery: `IF(${hours}>0,${p.recoveryValue}*${h.recDays}/${h.recDiv},0)`,
   sick: `IF(${p.sickBackToBack}=1,0,(${c.wage}+${c.tenure}+${c.recovery})*${sickRate})`,
   travel: `IF(OR(${p.travelBackToBack}=1,${hours}<=0),0,${p.monthlyTravel}/${hours})`,
   excellence: `IF(${p.excellenceBackToBack}=1,0,IF(${p.excellenceMode}="חודשי",IF(${hours}>0,${p.excellenceMonthly}/${hours},0),${p.excellenceHourly}))`,
   gift: `IF(OR(${p.holidayGiftBackToBack}=1,${hours}<=0),0,${h.giftMonthly}/${hours})`,
   niLow: `IF(${hours}>0,MIN(${h.gross},${p.maximum},${p.threshold})*${p.niLow}/${hours},0)`,
   niHigh: `IF(${hours}>0,MAX(0,MIN(${h.gross},${p.maximum})-${p.threshold})*${p.niHigh}/${hours},0)`,
   pension: `SUM(${c.wage}:${c.sick})*${b.pension}`,
   comp: `SUM(${c.wage}:${c.sick})*${b.comp}`,
   fund: `${h.fundBase}*${b.fund}`,
   travelPension: `${c.travel}*${p.travelPension}`,
   employer: `SUM(${c.wage}:${c.travelPension})`,
   materials: `IF(${hours}>0,${p.monthlyMaterials}/${hours},0)`,
   other: `IF(${hours}>0,${p.monthlyOther}/${hours},0)`,
   direct: `SUM(${c.employer}:${c.other})`,
   overhead: `${c.direct}*${b.overhead}`,
   profit: `SUM(${c.direct}:${c.overhead})*${b.profit}`,
   price: `SUM(${c.direct}:${c.profit})`,
   p125: `SUM(${h.cost125},${h.overhead125},${h.profit125})`,
   p150: `SUM(${h.cost150},${h.overhead150},${h.profit150})`,
  },
  rates:{
   wage: `1`,
   vacation: `IF(${base}>0,${c.vacation}/${base},0)`,
   tenure: `IF(${base}>0,${c.tenure}/${base},0)`,
   holiday: `IF(${p.holidayBackToBack}=1,"גב אל גב",${p.holidays}*${h.day}/${h.annual})`,
   recovery: `IF(${base}>0,${c.recovery}/${base},0)`,
   sick: `IF(${p.sickBackToBack}=1,"גב אל גב",${sickRate})`,
   travel: `IF(${p.travelBackToBack}=1,"גב אל גב",IF(${base}>0,${c.travel}/${base},0))`,
   excellence: `IF(${p.excellenceBackToBack}=1,"גב אל גב",IF(${base}>0,${c.excellence}/${base},0))`,
   gift: `IF(${p.holidayGiftBackToBack}=1,"גב אל גב",IF(${base}>0,${c.gift}/${base},0))`,
   niLow: `${p.niLow}`,
   niHigh: `${p.niHigh}`,
   pension: `${p.pension}`,
   comp: `${p.comp}`,
   fund: `${p.fund}`,
   travelPension: `IF(${p.travelBackToBack}=1,"גב אל גב",${p.travelPension})`,
   materials: `IF(${base}>0,${c.materials}/${base},0)`,
   other: `IF(${base}>0,${c.other}/${base},0)`,
   overhead: `${p.overhead}`,
   profit: `${p.profit}`,
  } as Partial<Record<PriceKey,string>>,
  helpers:{
   day: `IF(${week}<=5,8.4,7)`,
   vacDays: `IF(${week}<=5,IF(${years}<4,12,IF(${years}<5,13,IF(${years}<6,18,IF(${years}<8,19,23)))),IF(${years}<4,14,IF(${years}<5,15,IF(${years}<6,20,IF(${years}<8,21,26)))))`,
   recDays: `IF(${years}<3,7,IF(${years}<10,9,IF(${years}<15,10,IF(${years}<19,11,IF(${years}<24,12,13)))))`,
   annual: `${p.fullHours}*${p.months}`,
   vacDiv: `IF(${basis}="שעות עבודה בפועל",${h.annual}-${h.vacDays}*${h.day},${h.annual})`,
   recDiv: `IF(${basis}="שעות עבודה בפועל",${h.annual}-${h.vacDays}*${h.day},${h.annual}-(${p.holidays}+${h.vacDays})*${h.day})`,
   social: `SUM(${c.wage}:${c.sick})`,
   sectorVac: `IF(${hours}>0,(${sector}+${c.tenure})*${h.vacDays}*${h.day}/${h.vacDiv},0)`,
   sectorHoliday: `IF(${p.holidayBackToBack}=1,0,(${sector}+${c.tenure})*${p.holidays}*${h.day}/${h.annual})`,
   sectorSick: `IF(${p.sickBackToBack}=1,0,(${sector}+${c.tenure}+${c.recovery})*${sickRate})`,
   fundBase: `SUM(${sector},${h.sectorVac},${h.sectorHoliday},${c.recovery},${h.sectorSick})`,
   giftMonthly: `${p.giftAmount}*${p.giftCount}/${p.months}*IF(${hours}<=0,0,IF(${hours}>=${p.fullHours}/2,1,${hours}/${p.fullHours}))`,
   gross: `IF(${hours}>0,SUM(${h.social},${c.travel},${c.excellence},${c.gift})*${hours},0)`,
   regularNi: `MIN(MAX(0,${h.gross}),${p.maximum},${p.threshold})*${p.niLow}+MAX(0,MIN(MAX(0,${h.gross}),${p.maximum})-${p.threshold})*${p.niHigh}`,
   otEx: `IF(OR(${p.excellenceBackToBack}=1,${p.excellenceMode}="חודשי"),0,${p.excellenceHourly})`,
   wage125: `(${base}+${c.tenure})*1.25+${h.otEx}`,
   wage150: `(${base}+${c.tenure})*1.5+${h.otEx}`,
   otGross: `${h.wage125}*${hours125}+${h.wage150}*${hours150}`,
   fullNi: `MIN(MAX(0,(${h.gross}+${h.otGross})),${p.maximum},${p.threshold})*${p.niLow}+MAX(0,MIN(MAX(0,(${h.gross}+${h.otGross})),${p.maximum})-${p.threshold})*${p.niHigh}`,
   niRatio: `IF(${h.otGross}>0,(${h.fullNi}-${h.regularNi})/${h.otGross},0)`,
   ni125: `IF(${h.otGross}>0,${h.wage125}*${h.niRatio},(MIN(MAX(0,(${h.gross}+${h.wage125})),${p.maximum},${p.threshold})*${p.niLow}+MAX(0,MIN(MAX(0,(${h.gross}+${h.wage125})),${p.maximum})-${p.threshold})*${p.niHigh})-${h.regularNi})`,
   cost125: `(${base}+${c.tenure})*1.25*(1+${p.pension}+${p.otComp})+${h.otEx}+${h.ni125}`,
   overhead125: `${h.cost125}*${p.overhead}`,
   profit125: `(${h.cost125}+${h.overhead125})*${p.profit}`,
   ni150: `IF(${h.otGross}>0,${h.wage150}*${h.niRatio},(MIN(MAX(0,(${h.gross}+${h.wage150})),${p.maximum},${p.threshold})*${p.niLow}+MAX(0,MIN(MAX(0,(${h.gross}+${h.wage150})),${p.maximum})-${p.threshold})*${p.niHigh})-${h.regularNi})`,
   cost150: `(${base}+${c.tenure})*1.5*(1+${p.pension}+${p.otComp})+${h.otEx}+${h.ni150}`,
   overhead150: `${h.cost150}*${p.overhead}`,
   profit150: `(${h.cost150}+${h.overhead150})*${p.profit}`,
  },
 };
}
